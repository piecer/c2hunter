def _pattern(template: str) -> re.Pattern[str]:
    parts = template.split("/")
    expression = "/".join(
        "[^/]+" if part.startswith("{") and part.endswith("}") else re.escape(part)
        for part in parts
    )
    return re.compile(expression)


_MATCHERS = tuple((rule, _pattern(rule.template)) for rule in RULES)


def lookup_rule(method: str, path: str) -> RouteRule | None:
    """Match exactly the ASGI-decoded path; None means deny, not an exemption."""
    for rule, pattern in _MATCHERS:
        if rule.method == method and pattern.fullmatch(path) is not None:
            return rule
    return None
