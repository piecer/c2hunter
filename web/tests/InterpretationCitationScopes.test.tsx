import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import NetworkAIInterpretation from '../src/NetworkAIInterpretation';
import NetworkAnomalyPanel from '../src/NetworkAnomalyPanel';
const fixture = JSON.parse(execFileSync(process.env.C2HUNTER_TEST_PYTHON ?? resolve('../.venv/bin/python'), ['tests/network_report_fixture.py', '--citation'], { encoding: 'utf8', maxBuffer: 20000000 }));
const clients: QueryClient[] = [];
afterEach(() => clients.splice(0).forEach(client => client.clear()));
it('binds historical citations independently of active latest and never revives a latched scope after selection or remount', async () => {
  localStorage.setItem('c2hunter-report-language', 'en');
  const report = structuredClone(fixture.many), original = structuredClone(fixture.run);
  const old = { ...original, id: 'old' }, latest = { ...original, id: 'latest', status: 'ANALYZING' };
  const id = report.issues[19].id;
  vi.stubGlobal('fetch', vi.fn(async (input: unknown) => Response.json(String(input).endsWith('/ai-capabilities') ? { available: false } : String(input).endsWith('/ai-runs/old') ? old : String(input).endsWith('/ai-runs/latest') ? latest : { items: [latest, old] })));
  const client = new QueryClient({ defaultOptions: { queries: { retry: false, staleTime: Infinity } } }); clients.push(client);
  const job = { id: original.analysis_job_id, dataset_id: original.dataset_id, status: 'COMPLETED' };
  const tree = (source = report, key = 'stable') => <QueryClientProvider client={client}><NetworkAnomalyPanel report={source} job={job}><NetworkAIInterpretation key={key} jobId={job.id} completed/></NetworkAnomalyPanel></QueryClientProvider>;
  const view = render(tree());
  const open = () => fireEvent.click(screen.getByRole('button', { name: 'Open AI interpretation' }));
  await waitFor(() => expect(client.isFetching()).toBe(0)); open();
  fireEvent.click(screen.getByRole('button', { name: 'View saved run old' }));
  await waitFor(() => expect(screen.getAllByRole('button', { name: id })[0]).toBeEnabled());
  fireEvent.click(screen.getAllByRole('button', { name: id })[0]);
  expect(screen.getByRole('region', { name: 'Representative flow evidence' })).toHaveFocus();
  fireEvent.click(screen.getByRole('button', { name: /Hide representative evidence/ }));
  expect(screen.getByRole('heading', { name: 'Anomaly observed' })).toHaveFocus();
  open();
  const changed = structuredClone(report); changed.issues[0].examples[0].facts.tcp_sequence++;
  view.rerender(tree(changed)); open();
  expect(screen.getAllByRole('button', { name: id })[0]).toBeDisabled();
  fireEvent.click(screen.getByRole('button', { name: 'Follow latest run' }));
  view.rerender(tree()); open();
  fireEvent.click(screen.getByRole('button', { name: 'View saved run old' }));
  expect(screen.getAllByRole('button', { name: id })[0]).toBeDisabled();
  view.rerender(tree(report, 'remounted')); open();
  fireEvent.click(screen.getByRole('button', { name: 'View saved run old' }));
  expect(screen.getAllByRole('button', { name: id })[0]).toBeDisabled();
  const fresh = { ...old, id: 'fresh' };
  act(() => { client.setQueryData(['ai-run', 'fresh'], fresh); client.setQueryData(['ai-runs', job.id], { items: [latest, fresh, old] }); });
  fireEvent.click(await screen.findByRole('button', { name: 'View saved run fresh' }));
  expect(screen.getAllByRole('button', { name: id })[0]).toBeEnabled();
});
