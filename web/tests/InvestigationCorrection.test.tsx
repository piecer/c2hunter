it('L1 validated cancellation retry clears obsolete uncertainty and releases only after acknowledgment', async () => {
  const queued = parseJobWire('run', producer.fixtures.run_queued);
  const other = parseJob('run', { ...queued, id: 'f'.repeat(64) });
  const cancelled = parseJob('run', { ...queued, status: 'CANCELLED', revision: queued.revision + 1 });
  vi.spyOn(jobApi, 'capabilities').mockRejectedValue(new Error('Unavailable'));
  vi.spyOn(jobApi, 'history').mockResolvedValue({ items: [queued, other], next_cursor: null });
  const cancel = vi.spyOn(jobApi, 'cancel').mockRejectedValueOnce(new Error('receipt lost')).mockResolvedValueOnce(cancelled).mockImplementation(() => new Promise<never>(() => {}));
  render(<JobInvestigationPanel jobId="job"/>);
  fireEvent.click((await screen.findAllByRole('button', { name: /View saved run QUEUED/ }))[0]);
  fireEvent.click(screen.getByRole('button', { name: /Request cancellation/ }));
  await screen.findByText(/cancellation unconfirmed/);
  fireEvent.click(screen.getByRole('button', { name: /Request cancellation/ }));
  const acknowledge = await screen.findByRole('button', { name: 'Acknowledge retained outcome' });
  expect(screen.queryByText(/cancellation unconfirmed/)).not.toBeInTheDocument();
  expect(screen.getByText(/not proof of physical exit/)).toBeVisible();
  fireEvent.click(acknowledge);
  fireEvent.click(screen.getAllByRole('button', { name: /View saved run QUEUED/ })[1]);
  fireEvent.click(screen.getByRole('button', { name: /Request cancellation/ }));
  expect(cancel).toHaveBeenCalledTimes(3);
  expect(cancel.mock.calls[2][1].id).toBe(other.id);
});
